<?php
// Writes stdlib/phpx/curl_consts_gen.go from the curl constants of the php that runs it.
// usage: php phpx/scripts/gen-curl-consts.php  (from the repository root)
$c = get_defined_constants(true)["curl"];
$out = "//go:build phpx\n\npackage phpx\n\n// Code generated by phpx/scripts/gen-curl-consts.php; DO NOT EDIT.\n\n// phpxCurlIntConstants are the curl extension integer constants, with the values libcurl 8.x gives them in php 8.4.\nvar phpxCurlIntConstants = map[string]int64{\n";
$strs = [];
ksort($c);
foreach ($c as $k => $v) { if (is_int($v)) $out .= "\t\"$k\": $v,\n"; else $strs[$k] = $v; }
$out .= "}\n\n// phpxCurlStringConstants are the string ones.\nvar phpxCurlStringConstants = map[string]string{\n";
foreach ($strs as $k => $v) $out .= "\t\"$k\": " . json_encode($v) . ",\n";
$out .= "}\n";
file_put_contents("stdlib/phpx/curl_consts_gen.go", $out);
