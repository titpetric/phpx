<?php
// Writes stdlib/phpx/constants_gen.go from the constants of the php that runs it:
// the extensions phpx carries a surface for, each name registered only when the
// runtime has not defined it already.
// usage: php phpx/scripts/gen-consts.php  (from the repository root)
$all = get_defined_constants(true);
$cats = ['Core', 'pcre', 'standard', 'mbstring', 'date', 'json', 'hash', 'zlib', 'iconv', 'random', 'libxml', 'fileinfo', 'session', 'SPL', 'ctype', 'filter'];
// Values that name the machine php was built on rather than the language.
$skip = '/^(PHP_BINARY|PHP_OS|PHP_OS_FAMILY|PHP_VERSION|PHP_MAJOR_VERSION|PHP_MINOR_VERSION|PHP_RELEASE_VERSION|PHP_EXTRA_VERSION|PHP_VERSION_ID|PHP_SAPI|PHP_PREFIX|PHP_BINDIR|PHP_LIBDIR|PHP_DATADIR|PHP_SYSCONFDIR|PHP_LOCALSTATEDIR|PHP_CONFIG_FILE_PATH|PHP_CONFIG_FILE_SCAN_DIR|PHP_SHLIB_SUFFIX|PHP_MANDIR|PHP_EXTENSION_DIR|PEAR_.*|DEFAULT_INCLUDE_PATH|PHP_ZTS|PHP_DEBUG|ZEND_.*|PHP_MAXPATHLEN|PHP_FD_SETSIZE|E_ALL|STDIN|STDOUT|STDERR|PHP_CLI_PROCESS_TITLE|ICONV_.*VERSION|ICONV_IMPL|LIBXML_.*VERSION)$/';
$ints = []; $floats = []; $strs = []; $bools = [];
foreach ($cats as $cat) {
    foreach ($all[$cat] ?? [] as $k => $v) {
        if (preg_match($skip, $k) || in_array($k, ['TRUE', 'FALSE', 'NULL'], true)) continue;
        if (is_int($v)) $ints[$k] = $v;
        elseif (is_float($v)) $floats[$k] = $v;
        elseif (is_string($v)) $strs[$k] = $v;
        elseif (is_bool($v)) $bools[$k] = $v;
    }
}
ksort($ints); ksort($floats); ksort($strs); ksort($bools);
$out = "//go:build phpx\n\npackage phpx\n\n// Code generated by phpx/scripts/gen-consts.php; DO NOT EDIT.\n\n// phpxGenIntConstants are the integer constants of the extensions the runtime carries, with php 8.4's values.\nvar phpxGenIntConstants = map[string]int64{\n";
foreach ($ints as $k => $v) $out .= "\t\"$k\": $v,\n";
$out .= "}\n\n// phpxGenFloatConstants are the float ones.\nvar phpxGenFloatConstants = map[string]float64{\n";
foreach ($floats as $k => $v) {
    $lit = is_nan($v) ? 'math.NaN()' : (is_infinite($v) ? ($v > 0 ? 'math.Inf(1)' : 'math.Inf(-1)') : var_export($v, true));
    if (!str_contains($lit, '.') && !str_contains($lit, 'math') && !str_contains($lit, 'E')) $lit .= '.0';
    $out .= "\t\"$k\": $lit,\n";
}
$out .= "}\n\n// phpxGenStringConstants are the string ones.\nvar phpxGenStringConstants = map[string]string{\n";
foreach ($strs as $k => $v) $out .= "\t\"$k\": " . json_encode($v, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . ",\n";
$out .= "}\n\n// phpxGenBoolConstants are the boolean ones.\nvar phpxGenBoolConstants = map[string]bool{\n";
foreach ($bools as $k => $v) $out .= "\t\"$k\": " . ($v ? 'true' : 'false') . ",\n";
$out .= "}\n";
$out = str_replace("package phpx\n", "package phpx\n\nimport \"math\"\n", $out);
file_put_contents('stdlib/phpx/constants_gen.go', $out);
echo count($ints), " ints, ", count($floats), " floats, ", count($strs), " strings, ", count($bools), " bools\n";
